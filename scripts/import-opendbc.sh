#!/bin/sh
# Imports real ECU identification replies from commaai/opendbc (MIT) as sim test data (issues #15, #12).
# opendbc keeps each car's firmware versions in opendbc/car/<make>/fingerprints.py, as the reply to
# a ReadDataByIdentifier request with the response's fixed prefix removed. The prefix differs per make.
#
# One make, engine and transmission only (VW/Audi: the reply to a multi-DID read, minus 0x62):
#   scripts/import-opendbc.sh <make> <commit> <out.toml> <CAR>...
#   scripts/import-opendbc.sh volkswagen 229dc7062d8986b4f954c7c97875b4ffd0044d12 \
#       crates/obdcracker-sim/fixtures/opendbc-vag.toml AUDI_Q5_MK1 AUDI_A3_MK3 PORSCHE_MACAN_MK1
#
# Any ECU of several makes, each reply rebuilt into its complete payload (the first one opendbc lists
# for that car and ECU; hyundai, ford and honda):
#   scripts/import-opendbc.sh --full <commit> <out.toml> <make>:<CAR>:<ecu>...
#   scripts/import-opendbc.sh --full 229dc7062d8986b4f954c7c97875b4ffd0044d12 \
#       crates/obdcracker-sim/fixtures/opendbc-other-makes.toml ford:FORD_ESCAPE_MK4_5:eps ...
#
# Toyota takes a file of its own, and names the ECU's request ID where a car has the ECU at two
# (<make>:<CAR>:<ecu>[@<request ID>]). Its sub-address replies (0x750) get a `sub_address` field:
#   scripts/import-opendbc.sh --full 229dc7062d8986b4f954c7c97875b4ffd0044d12 \
#       crates/obdcracker-sim/fixtures/opendbc-toyota.toml toyota:TOYOTA_CAMRY:engine@0x700 \
#       toyota:TOYOTA_CAMRY:fwdRadar ...
#
# Add the commit to docs/third-party.md.
set -e
full=
if [ "$1" = --full ]; then
	full=1
	shift
	[ $# -ge 3 ] || { sed -n 2,23p "$0" >&2; exit 2; }
	commit=$1 out=$2
	shift 2
	makes=$(printf '%s\n' "$@" | cut -d: -f1 | sort -u)
else
	[ $# -ge 4 ] || { sed -n 2,23p "$0" >&2; exit 2; }
	makes=$1 commit=$2 out=$3
	shift 3
	set -- "$makes" "$@"
fi
tmp=$(mktemp -d)
# The output is written beside its destination, so the final mv is a rename on one filesystem
# (atomic), never a copy that an interruption could leave half done.
staged=$(mktemp "$out.XXXXXX")
trap 'rm -rf "$tmp" "$staged"' EXIT
for make in $makes; do
	case $make in
	*[!a-z]* | '') echo "bad make name: $make" >&2; exit 2 ;;
	esac
	curl -fsSL "https://raw.githubusercontent.com/commaai/opendbc/$commit/opendbc/car/$make/fingerprints.py" \
		-o "$tmp/$make.py"
done
# -I: the downloaded files are only read, never imported.
# Moved into place only on success, so a failed run leaves the existing fixture untouched.
python3 -I - "$tmp" "$full" "$commit" "$@" >"$staged" <<'PY'
import ast, re, sys

tmp, full, commit, args = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]


CAR = re.compile(r"  CAR\.(\w+): \{")
KEY = re.compile(r"    \(Ecu\.(\w+), (0x[0-9a-fA-F]+), (None|0x[0-9a-fA-F]+)\): \[\n")
REPLY = re.compile(r"      (b'.*'|b\".*\"),\n")


def parse(make):
    # Every reply as (car, ecu, request ID, sub-address or None, data), in file order. A line that
    # sets the car or the key, or holds a reply, and isn't read exactly ends the import: skipping
    # it would drop its replies, or file them under the previous car or key.
    car = key = None
    entries = []
    for number, line in enumerate(open(f"{tmp}/{make}.py"), 1):
        where = f"{make}.py:{number}"
        if m := CAR.match(line):
            car = m.group(1)
        elif line.startswith("  CAR") or line.startswith("  ("):
            sys.exit(f"{where}: can't read the car {line.strip()!r}")
        elif line.startswith("    ("):
            m = KEY.fullmatch(line)
            if not (car and m):
                sys.exit(f"{where}: can't read the key {line.strip()!r} under {car}")
            sub_address = None if m.group(3) == "None" else int(m.group(3), 16)
            key = (m.group(1), int(m.group(2), 16), sub_address)
        elif line.startswith("  }") or line.startswith("}"):
            car = key = None
        elif line.startswith("      "):
            m = REPLY.fullmatch(line)
            if not (car and key and m):
                sys.exit(f"{where}: can't read the reply {line.strip()!r} under {car} {key}")
            entries.append((car, *key, ast.literal_eval(m.group(1))))
    return entries


if not full:
    make, cars = args[0], args[1:]
    entries = [
        e for e in parse(make) if e[0] in cars and e[1] in ("engine", "transmission")
    ]
    if any(e[3] is not None for e in entries):
        sys.exit("an engine or transmission reply has a sub-address; the format has no field for it")
    missing = set(cars) - {e[0] for e in entries}
    if missing:
        sys.exit(f"no engine or transmission entries for {', '.join(sorted(missing))}")

    print(f"# Generated by scripts/import-opendbc.sh from commaai/opendbc (MIT), commit {commit},")
    print(f"# opendbc/car/{make}/fingerprints.py. Each `data` is a module's reply to a multi-DID")
    print("# ReadDataByIdentifier, without the 0x62 service ID. Don't edit; re-run the script.")
    for car, ecu, request_id, _, data in entries:
        print()
        print("[[reply]]")
        print(f'car = "{car}"')
        print(f'ecu = "{ecu}"')
        print(f"request_id = 0x{request_id:03X}")
        print(f'data = "{data.hex(" ").upper()}"')
    sys.exit(0)

# What each make's query config (FW_QUERY_CONFIG in opendbc/car/<make>/values.py) strips from the
# positive response before storing it: Hyundai only 0x62, so its stored value starts with the echoed
# DID 0xF100; Ford 0x62 0xF188, and Honda 0x62 0xF181, so theirs hold just the data.
PREFIX = {
    "hyundai": bytes([0x62]),
    "ford": bytes([0x62, 0xF1, 0x88]),
    "honda": bytes([0x62, 0xF1, 0x81]),
}


def toyota_payload(request_id, value):
    # Toyota asks each ECU up to three ways (FW_QUERY_CONFIG in opendbc/car/toyota/values.py) and
    # stores the answer without the prefix of whichever request got it, so the prefix is worked out
    # from the value. A counted one (a count of 16-byte records, 1 to 3) answers mode 09 PID 04
    # (49 04) from the OBD-II engine address 0x7E0, and UDS F181 (62 F1 81) from the others; a bare
    # 16-byte record whose first byte isn't a count answers KWP2000 1A 88 01 (5A 88 01). A value of
    # any other shape fails the import.
    records, extra = divmod(len(value) - 1, 16)
    if len(value) == 16 and not 1 <= value[0] <= 3:
        return bytes([0x5A, 0x88, 0x01]) + value
    if extra == 0 and 1 <= records <= 3 and value[0] == records:
        prefix = bytes([0x49, 0x04]) if request_id == 0x7E0 else bytes([0x62, 0xF1, 0x81])
        return prefix + value
    sys.exit(f"toyota 0x{request_id:03X}: can't tell which request the reply {value!r} answers")


def response_id(request_id):
    # opendbc's uds.get_rx_addr_for_tx_addr: +8 for 11-bit IDs, the last two bytes swapped for 29-bit.
    if request_id < 0xFFF8:
        return request_id + 8
    if 0x10000000 < request_id < 0xFFFFFFFF:
        return (request_id & 0xFFFF0000) | (request_id << 8 & 0xFF00) | (request_id >> 8 & 0xFF)
    sys.exit(f"no response ID rule for request ID 0x{request_id:X}")


specs = []
for arg in args:
    parts = arg.split(":")
    if len(parts) != 3 or not all(parts):
        sys.exit(f"expected <make>:<CAR>:<ecu>[@<request ID>], got {arg!r}")
    make, car, ecu = parts
    request_id = None
    if "@" in ecu:
        ecu, _, wanted = ecu.partition("@")
        if not re.fullmatch(r"0x[0-9a-fA-F]+", wanted):
            sys.exit(f"bad request ID in {arg!r}")
        request_id = int(wanted, 16)
    if make not in PREFIX and make != "toyota":
        sys.exit(f"no payload rule for make {make!r}")
    if (make, car, ecu, request_id) in specs:
        sys.exit(f"{arg} given twice")
    specs.append((make, car, ecu, request_id))

if any(spec[0] == "toyota" for spec in specs) and any(spec[0] != "toyota" for spec in specs):
    sys.exit("toyota takes a file of its own: its reply forms differ from the other makes'")

parsed = {make: parse(make) for make in sorted({spec[0] for spec in specs})}
if specs[0][0] == "toyota":
    print(f"# Generated by scripts/import-opendbc.sh --full from commaai/opendbc (MIT), commit {commit},")
    print("# opendbc/car/toyota/fingerprints.py. Each `payload` is a module's complete positive reply to")
    print("# the request that identifies it: mode 09 PID 04 (49 04) from the engine at 0x7E0, UDS F181")
    print("# (62 F1 81, a count and 16-byte records) or KWP2000 1A 88 01 (5A 88 01, one record). opendbc")
    print("# stores the reply without that prefix and not which request it was, so the importer works it")
    print("# out from the value's shape. A `sub_address` is the ISO-TP extended-address byte (the first")
    print("# byte of each frame, both ways). The first reply opendbc lists is kept for each car and ECU.")
    print("# Don't edit; re-run the script.")
else:
    print(f"# Generated by scripts/import-opendbc.sh --full from commaai/opendbc (MIT), commit {commit},")
    print("# opendbc/car/<make>/fingerprints.py. Each `payload` is a module's complete positive reply to a")
    print("# one-DID ReadDataByIdentifier (Hyundai F100, Ford F188, Honda F181), rebuilt from opendbc's")
    print("# stored value and its per-make prefix. The first reply opendbc lists is kept for each car and")
    print("# ECU. Don't edit; re-run the script.")
for make, car, ecu, wanted in specs:
    found = [e for e in parsed[make] if e[0] == car and e[1] == ecu and wanted in (None, e[2])]
    if not found:
        sys.exit(f"no {ecu} entries for {make} {car}")
    ids = {(e[2], e[3]) for e in found}
    if len(ids) != 1:
        sys.exit(f"{make} {car} {ecu} has several request IDs; name one as {ecu}@0x...")
    request_id, sub_address, value = found[0][2], found[0][3], found[0][4]
    if make == "toyota":
        payload = toyota_payload(request_id, value)
    elif sub_address is None:
        payload = PREFIX[make] + value
    else:
        sys.exit(f"{make} {car} {ecu} has a sub-address, which {make}'s format has no field for")
    print()
    print("[[reply]]")
    print(f'make = "{make}"')
    print(f'car = "{car}"')
    print(f'ecu = "{ecu}"')
    print(f"request_id = 0x{request_id:03X}")
    print(f"response_id = 0x{response_id(request_id):03X}")
    if sub_address is not None:
        print(f"sub_address = 0x{sub_address:02X}")
    print(f'payload = "{payload.hex(" ").upper()}"')
PY
# mktemp makes it private (0600); a fixture is an ordinary readable file.
chmod 644 "$staged"
mv "$staged" "$out"
